#!/usr/bin/env python3
"""
theme_patch.py - post-build patch of TWRP's generated portrait.xml.

Runs from BOARD_RECOVERY_IMAGE_PREPARE after the recovery ramdisk has been
assembled, so the patch is applied to the theme generated by soong's
copyTheme (out/.../recovery/root/twres/portrait.xml) instead of shipping a
pre-built copy in the device tree.

Patches applied (xiaomi monet, stock TWRP source untouched):
  1. "Disable AVB2.0" (Advanced menu): TWRP's built-in disableAVB2 action
     only touches the top-level vbmeta flags WITHOUT re-signing (breaks the
     AVB signature) and never processes vbmeta_system/vendor/product/odm.
     Point the button at /system/bin/avb_disable instead, which disables
     verification+verity on all five vbmeta partitions and re-signs them.
  2. "Automatically disable AVB2.0 after flashing ROM" checkbox (Settings):
     it calls TWRP's built-in Disable_AVB2 from twinstall.cpp (the same
     broken path) - remove it so it can't be enabled by mistake.
  3. "Install TWRP App" (Advanced menu): remove the entry (tw_app_install_*
     conditions would otherwise surface it).

Usage: theme_patch.py <portrait.xml>  (patches the file in place)
Exit code 0 on success, 1 if a required pattern is missing.

SPDX-License-Identifier: Apache-2.0
"""

import re
import sys


def patch_avb_button(xml):
    """Point the Disable AVB2.0 button at avb_disable (re-signing tool)."""
    old = ('<action function="set">tw_action=disableAVB2</action>')
    new = ('<action function="set">tw_action=cmd</action>\n'
           '\t\t\t\t\t\t<action function="set">'
           'tw_action_param=/system/bin/avb_disable</action>')
    if old not in xml:
        return xml, False
    return xml.replace(old, new), True


def remove_auto_disable_checkbox(xml):
    """Drop the Settings 'auto disable AVB2.0 after ROM flash' checkbox."""
    pat = re.compile(
        r'\s*<listitem name="\{@auto_disable_avb2=.*?</listitem>', re.S)
    new, n = pat.subn('', xml)
    return new, n > 0


def remove_install_twrp_app(xml):
    """Drop the Advanced menu TWRP App entries (install + uninstall)."""
    pat = re.compile(
        r'\s*<listitem name="\{@reboot_install_app_hdr=Install TWRP App\}"'
        r'>.*?</listitem>', re.S)
    new, n = pat.subn('', xml)
    pat = re.compile(
        r'\s*<listitem name="\{@uninstall_twrp_system_app='
        r'Uninstall TWRP App from System\}">.*?</listitem>', re.S)
    new, n2 = pat.subn('', new)
    return new, (n + n2) > 0


def main(argv):
    if len(argv) != 1:
        print('usage: theme_patch.py <portrait.xml>', file=sys.stderr)
        return 1
    path = argv[0]
    with open(path, 'r', encoding='utf-8') as f:
        xml = f.read()

    ok = True
    xml, hit = patch_avb_button(xml)
    if not hit:
        print(f'{path}: WARNING: disableAVB2 button pattern not found',
              file=sys.stderr)
        ok = False
    xml, hit = remove_auto_disable_checkbox(xml)
    if not hit:
        print(f'{path}: WARNING: auto_disable_avb2 listitem not found',
              file=sys.stderr)
        ok = False
    xml, hit = remove_install_twrp_app(xml)
    if not hit:
        print(f'{path}: WARNING: Install TWRP App listitem not found',
              file=sys.stderr)
        ok = False

    if not ok:
        return 1

    with open(path, 'w', encoding='utf-8') as f:
        f.write(xml)
    print(f'{path}: theme patched (avb_disable button, auto-avb checkbox, '
          f'TWRP App entry)')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
